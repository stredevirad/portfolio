// Converts project images in assets-src/projects/*.png into AVIF + WebP at a few widths,
// writes them to public/images/, and emits src/content/images.generated.ts with intrinsic sizes.
// Run: npm run images   (outputs are committed, so CI does not need to run this)
import { readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'assets-src/projects';
const OUT = 'public/images';
const WIDTHS = [480, 960, 1440];

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => f.endsWith('.png')).sort();
const manifest = {};

for (const file of files) {
  const name = path.basename(file, '.png');
  const input = sharp(path.join(SRC, file));
  const meta = await input.metadata();
  const widths = WIDTHS.filter((w) => w < meta.width);
  widths.push(Math.min(meta.width, 1600));
  const unique = [...new Set(widths)].sort((a, b) => a - b);
  for (const w of unique) {
    const resized = sharp(path.join(SRC, file)).resize({ width: w });
    await resized.clone().avif({ quality: 52, effort: 6 }).toFile(path.join(OUT, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: 78 }).toFile(path.join(OUT, `${name}-${w}.webp`));
  }
  manifest[name] = { width: meta.width, height: meta.height, widths: unique };
  console.log(`${name}: ${meta.width}x${meta.height} -> ${unique.join(', ')}`);
}

const ts = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const;
export type ImageName = keyof typeof images;
`;
await writeFile('src/content/images.generated.ts', ts);
